for each row execute function public.emit_school_delete_realtime_event();

do $block$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'school_realtime_events'
  ) then
    alter publication supabase_realtime
    add table public.school_realtime_events;
  end if;
end
$block$;
